// Turns tokens/ into every format the apps read:
//
//   dist/tokens.css          CSS variables: light, dark by the OS, or forced by data-theme="light|dark"
//   dist/tokens-class.css    the same, switched by a .dark class (VitePress and other class-switched sites)
//   dist/tokens.json         { light, dark, base }, for scripts (Python, Node)
//   dist/index.js, .d.ts     the same values as typed constants
//   Sources/IscorDesign/Tokens.swift   for SwiftUI and AppKit/UIKit apps (committed: SwiftPM reads the repo)
//   packages/vscode/themes/  the VS Code themes, from theme.template.json (committed: the extension ships them)
//   packages/xcode/          the Xcode themes, from theme.template.json (committed: copied into Xcode by hand)
//
//   node build/build.mjs           write everything
//   node build/build.mjs --check   fail if a committed generated file differs from what the tokens give
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (path) => JSON.parse(readFileSync(join(root, path), 'utf8'))
const GENERATED = 'Generated by build/build.mjs from tokens/: do not edit, change the tokens.'

// ---------- The tokens ----------

/** A DTCG group flattened to { "color.ink": token }. */
function flatten(group, prefix = []) {
  const out = {}
  for (const [key, value] of Object.entries(group)) {
    if (key.startsWith('$')) continue
    if (value && typeof value === 'object' && '$value' in value) out[[...prefix, key].join('.')] = value
    else Object.assign(out, flatten(value, [...prefix, key]))
  }
  return out
}

export function loadTokens() {
  const light = flatten(read('tokens/color.light.json'))
  const dark = flatten(read('tokens/color.dark.json'))
  const base = flatten(read('tokens/base.json'))
  const missing = [...Object.keys(light).filter((k) => !(k in dark)), ...Object.keys(dark).filter((k) => !(k in light))]
  if (missing.length) throw new Error(`tokens defined in one scheme only: ${missing.join(', ')}`)
  for (const [name, token] of Object.entries({ ...light, ...dark }))
    if (token.$type === 'color' && !/^#[0-9a-f]{6}([0-9a-f]{2})?$/.test(token.$value))
      throw new Error(`${name}: ${token.$value} is not a lowercase #rrggbb or #rrggbbaa colour`)
  return { light, dark, base }
}

const short = (name) => name.split('.').pop() // color.ink-soft → ink-soft
const camel = (name) => short(name).replace(/-(\w)/g, (_, c) => c.toUpperCase()) // ink-soft → inkSoft, card-2 → card2

/** #rrggbbaa → rgba(r, g, b, a), so the CSS reads the way it always has. */
function cssColor(hex) {
  if (hex.length === 7) return hex
  const [r, g, b, a] = [1, 3, 5, 7].map((i) => parseInt(hex.slice(i, i + 2), 16))
  return `rgba(${r}, ${g}, ${b}, ${Math.round((a / 255) * 100) / 100})`
}

const cssValue = (token) =>
  token.$type === 'color'
    ? cssColor(token.$value)
    : Array.isArray(token.$value)
      ? token.$value.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ')
      : token.$value

/** The CSS name of a token: the colours keep their bare names (--ink), radii are --r-*, fonts --font and --mono. */
function cssName(name) {
  if (name.startsWith('color.')) return `--${short(name)}`
  if (name.startsWith('radius.')) return `--r-${short(name)}`
  if (name === 'font.family') return '--font'
  if (name === 'font.mono') return '--mono'
  throw new Error(`no CSS name for ${name}`)
}

const declarations = (tokens, indent) =>
  Object.entries(tokens)
    .map(([name, token]) => `${indent}${cssName(name)}: ${cssValue(token)};`)
    .join('\n')

// ---------- The formats ----------

function css({ light, dark, base }) {
  return `/* @iscor/design, the Estuary theme. ${GENERATED} */

:root,
:root[data-theme='light'] {
${declarations(light, '  ')}
${declarations(base, '  ')}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${declarations(dark, '    ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${declarations(dark, '  ')}
  color-scheme: dark;
}
`
}

function cssClass({ light, dark, base }) {
  return `/* @iscor/design, the Estuary theme, switched by a .dark class on the root (VitePress and the like). ${GENERATED} */

:root {
${declarations(light, '  ')}
${declarations(base, '  ')}
  color-scheme: light;
}

:root.dark {
${declarations(dark, '  ')}
  color-scheme: dark;
}
`
}

const values = (tokens) => Object.fromEntries(Object.entries(tokens).map(([name, token]) => [short(name), token.$value]))

function json({ light, dark, base }) {
  return JSON.stringify({ light: values(light), dark: values(dark), base: values(base) }, null, 2) + '\n'
}

function js({ light, dark, base }) {
  return `// ${GENERATED}
export const light = ${JSON.stringify(values(light), null, 2)}
export const dark = ${JSON.stringify(values(dark), null, 2)}
export const base = ${JSON.stringify(values(base), null, 2)}
`
}

function dts({ light }) {
  const keys = Object.keys(values(light))
    .map((k) => `  readonly '${k}': string`)
    .join('\n')
  return `// ${GENERATED}
/** A colour scheme's tokens, as #rrggbb or #rrggbbaa. */
export interface Scheme {
${keys}
}
export declare const light: Scheme
export declare const dark: Scheme
export declare const base: {
  readonly xl: string
  readonly lg: string
  readonly md: string
  readonly pill: string
  readonly family: readonly string[]
  readonly mono: readonly string[]
}
`
}

function swift({ light, dark, base }) {
  const hex = (v) => `0x${v.slice(1, 7).toUpperCase()}`
  const alpha = (v) => (v.length === 9 ? Math.round((parseInt(v.slice(7), 16) / 255) * 100) / 100 : 1)
  const colour = (name) => {
    const l = light[name].$value
    const d = dark[name].$value
    const args = [
      `light: ${hex(l)}`,
      ...(alpha(l) !== 1 ? [`lightAlpha: ${alpha(l)}`] : []),
      `dark: ${hex(d)}`,
      ...(alpha(d) !== 1 ? [`darkAlpha: ${alpha(d)}`] : []),
    ]
    const doc = light[name].$description ? `    /// ${light[name].$description}\n` : ''
    return `${doc}    public static let ${camel(name)} = EstuaryColor(${args.join(', ')})`
  }
  const radius = (k) => `        public static let ${k}: CGFloat = ${parseFloat(base[`radius.${k}`].$value)}`
  return `// ${GENERATED}
import CoreGraphics

/// The Estuary theme's tokens.
public enum Estuary {
${Object.keys(light).map(colour).join('\n')}

    /// Corner radii, in points.
    public enum Radius {
${['xl', 'lg', 'md', 'pill'].map(radius).join('\n')}
    }

    /// The typeface's family name (the app ships the font: Outfit, SIL OFL).
    public static let fontFamily = "${base['font.family'].$value[0].replace(' Variable', '')}"
}
`
}

/** The template's {color.x} references resolved in one scheme. */
function vscodeTheme(template, scheme, name, type) {
  const resolve = (value) =>
    typeof value === 'string'
      ? value.replace(/\{(color\.[\w-]+)\}/g, (_, ref) => {
          if (!scheme[ref]) throw new Error(`theme.template.json: unknown token ${ref}`)
          return scheme[ref].$value
        })
      : Array.isArray(value)
        ? value.map(resolve)
        : value && typeof value === 'object'
          ? Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v)]))
          : value
  return JSON.stringify({ $schema: 'vscode://schemas/color-theme', name, type, ...resolve(template) }, null, 2) + '\n'
}

/** An Xcode .xccolortheme (a plist) from packages/xcode/theme.template.json, in one scheme. */
function xcodeTheme(template, scheme) {
  const colour = (ref) => {
    const token = scheme[ref.slice(1, -1)]
    if (!token) throw new Error(`packages/xcode/theme.template.json: unknown token ${ref}`)
    const v = token.$value
    const channels = [1, 3, 5, 7].map((i) => (i < v.length ? parseInt(v.slice(i, i + 2), 16) / 255 : 1))
    return channels.map((c) => +c.toFixed(6)).join(' ')
  }
  const font = (face) => `${face} - ${template.fontSize.toFixed(1)}`
  const entry = (key, value, indent) => `${indent}<key>${key}</key>\n${indent}${value}`
  const string = (s) => `<string>${s}</string>`
  const dict = (pairs, indent) => `<dict>\n${pairs.map(([k, v]) => entry(k, v, indent + '\t')).join('\n')}\n${indent}</dict>`
  const syntax = Object.entries(template.syntax)
  const top = [
    ...Object.entries(template.colors).map(([k, ref]) => [k, string(colour(ref))]),
    ...Object.entries(template.consoleFonts).map(([k, face]) => [k, string(font(face))]),
    ['DVTFontAndColorVersion', '<integer>1</integer>'],
    ['DVTLineSpacing', `<real>${template.lineSpacing}</real>`],
    [
      'DVTSourceTextSyntaxColors',
      dict(
        syntax.map(([k, [ref]]) => [k, string(colour(ref))]),
        '\t',
      ),
    ],
    [
      'DVTSourceTextSyntaxFonts',
      dict(
        syntax.map(([k, [, face]]) => [k, string(font(face))]),
        '\t',
      ),
    ],
  ]
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${GENERATED} -->
<plist version="1.0">
${dict(top, '')}
</plist>
`
}

// ---------- Writing them ----------

export function outputs() {
  const tokens = loadTokens()
  const template = read('packages/vscode/theme.template.json')
  const xcode = read('packages/xcode/theme.template.json')
  return {
    built: {
      'dist/tokens.css': css(tokens),
      'dist/tokens-class.css': cssClass(tokens),
      'dist/tokens.json': json(tokens),
      'dist/index.js': js(tokens),
      'dist/index.d.ts': dts(tokens),
    },
    committed: {
      'Sources/IscorDesign/Tokens.swift': swift(tokens),
      'packages/vscode/themes/estuary-light-color-theme.json': vscodeTheme(template, tokens.light, 'Estuary Light', 'light'),
      'packages/vscode/themes/estuary-dark-color-theme.json': vscodeTheme(template, tokens.dark, 'Estuary Dark', 'dark'),
      'packages/xcode/Estuary Light.xccolortheme': xcodeTheme(xcode, tokens.light),
      'packages/xcode/Estuary Dark.xccolortheme': xcodeTheme(xcode, tokens.dark),
    },
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { built, committed } = outputs()
  if (process.argv.includes('--check')) {
    const stale = Object.entries(committed).filter(
      ([path, text]) => !existsSync(join(root, path)) || readFileSync(join(root, path), 'utf8') !== text,
    )
    if (stale.length) {
      console.error(`Out of date with tokens/: ${stale.map(([p]) => p).join(', ')}. Run npm run build.`)
      process.exit(1)
    }
    console.log('Generated files are up to date.')
  } else {
    for (const [path, text] of Object.entries({ ...built, ...committed })) {
      mkdirSync(dirname(join(root, path)), { recursive: true })
      writeFileSync(join(root, path), text)
    }
    console.log(`Wrote ${Object.keys(built).length + Object.keys(committed).length} files.`)
  }
}
